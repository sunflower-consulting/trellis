#!/usr/bin/env python3
"""Render the sources into one file that consumers vendor.

WHY A BUNDLE AND NOT A DEPENDENCY.

The two consumers cannot take one. The harness must run offline with no corpus, no
network and no hardware, which rules out fetching this at run time; and `doc-engine`
has no package install at all, only typst and two python libraries. A git submodule
is worse than either: an uninitialised one is an EMPTY DIRECTORY rather than an
error, and a Control Mapping appendix that renders zero rows without complaining is
the exact failure mode this dataset exists to prevent.

So: one generated file, checked in on both sides, with a digest. The copy is the
deliberate act that pins what a report cited, and `git diff` on one YAML file is a
reviewable regulatory change.

WHY THE DIGEST.

Two vendored copies drift in opposite directions the first week nobody is watching:
the harness updates because a run needed a new obligation, `doc-engine` does not
because nobody rebuilt a report. Then the gate cannot resolve an id and the fastest
fix under deadline is to loosen the gate. `body_sha256` is over the CONTENT only, so
a consumer can assert it holds the bytes it thinks it holds.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

import yaml


class _Plain(yaml.SafeDumper):
    """No anchors in the published artefact.

    PyYAML emits `&id001`/`*id001` whenever two entries share a list object - which
    happens constantly here, because many techniques map to the same obligations. It
    is valid YAML and it is hostile: a reader scanning for what a technique maps to
    finds a reference, and a parser in another language may or may not resolve it.
    """

    def ignore_aliases(self, data):
        return True


ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist" / "snapshot.yaml"

#: Bumped by hand when the SHAPE changes, not when the content does. A consumer
#: pinned to 1 can read any snapshot that carries 1 and should refuse a 2.
SCHEMA_VERSION = 1


def _revision() -> str:
    """The commit these sources came from, or "working-tree" when they are dirty.

    Never silently reports a clean sha for an edited tree: a report whose provenance
    says it cited revision abc123 when the file on disk differed is worse than one
    that says it cited an uncommitted working tree.
    """
    try:
        sha = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"],
                             capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "-C", str(ROOT), "status", "--porcelain"],
                               capture_output=True, text=True, check=True).stdout.strip()
        return f"{sha}-dirty" if dirty else sha
    except (subprocess.CalledProcessError, FileNotFoundError, OSError):
        return "working-tree"


def _load_dir(path: Path) -> dict:
    """Every YAML file under `path`, keyed by its `id` where it has one."""
    out: dict = {}
    if not path.is_dir():
        return out
    for p in sorted(path.rglob("*.yaml")):
        doc = yaml.safe_load(p.read_text(encoding="utf-8"))
        if doc is None:
            continue
        key = doc.get("id") if isinstance(doc, dict) else None
        out[key or p.relative_to(path).as_posix()] = doc
    return out


def _load_file(path: Path) -> dict:
    if not path.is_file():
        return {}
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def build() -> dict:
    body = {
        "obligations": _load_dir(ROOT / "obligations"),
        "crosswalk": _load_file(ROOT / "crosswalk" / "llm-techniques.yaml"),
        "unmapped": _load_file(ROOT / "crosswalk" / "_unmapped.yaml"),
        "taxonomy": _load_file(ROOT / "taxonomy" / "llm-techniques.yaml"),
        "tier": _load_file(ROOT / "tier" / "ai-act.yaml"),
        "calendar": _load_file(ROOT / "calendar.yaml"),
    }
    # Over the content only, and over a canonical serialisation: a digest that moved
    # when a key was reordered would be a digest nobody trusts and everyone bypasses.
    digest = hashlib.sha256(
        json.dumps(body, sort_keys=True, separators=(",", ":"),
                   default=str).encode()).hexdigest()
    return {
        "schema_version": SCHEMA_VERSION,
        "generated_from": _revision(),
        "body_sha256": digest,
        **body,
    }


def main(argv: list[str]) -> int:
    doc = build()
    DIST.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# GENERATED by bin/bundle.py. Do not edit.\n"
        "#\n"
        "# This is the file consumers vendor. Edit the sources and regenerate; a hand\n"
        "# edit here is invisible to the sources and fails `tests/test_bundle.py`,\n"
        "# which round-trips the two against each other in both directions.\n")
    DIST.write_text(header + yaml.dump(doc, Dumper=_Plain, sort_keys=False,
                                       width=100, allow_unicode=True,
                                       default_flow_style=False), encoding="utf-8")
    print(f"wrote {DIST.relative_to(ROOT)}")
    print(f"  obligations: {len(doc['obligations'])}")
    print(f"  techniques:  {len(doc.get('taxonomy', {}).get('techniques', {}))}")
    print(f"  revision:    {doc['generated_from']}")
    print(f"  body_sha256: {doc['body_sha256'][:16]}")
    if "-dirty" in doc["generated_from"]:
        print("  note: built from an edited working tree, and says so")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
